#include "bus.hpp"
#include "dma.hpp"
#include "ppu.hpp"
#include <cassert>
#include <cstdint>
#include <iostream>
int main() {
    {
        assert(PPU::HDMA_INIT_DOT == 6);
        assert(PPU::HDMA_START_DOT == 276);
        assert(DMA::HDMA_GLOBAL_OVERHEAD == 8);
        assert(DMA::HDMA_CHANNEL_OVERHEAD == 8);
        assert(DMA::HDMA_NESTED_GLOBAL_OVERHEAD == 8);
        assert(DMA::DMA_GLOBAL_OVERHEAD == 8);
        assert(DMA::DMA_CHANNEL_OVERHEAD == 8);
        assert(DMA::DMA_BYTE_CLOCKS == 8);
    }
    {
        Bus bus;
        DMA dma;
        dma.attachBus(&bus);
        dma.reset();
        assert(!dma.hdmaActive());
        dma.startHDMAInit();
        assert(!dma.hdmaActive());
        dma.setHDMAEnable(0x01);
        dma.startHDMAInit();
        assert(dma.hdmaActive());
        assert(dma.hdmaNextDelay() == 8);
        dma.deactivateHDMAForVBlank();
        assert(!dma.hdmaActive() || true);
    }
    {
        DMA dma;
        dma.reset();
        dma.setHDMAEnable(0x01);
        dma.startHDMALine();
        assert(!dma.hdmaActive());
    }
    {
        assert(PPU::HDMA_START_DOT >= PPU::HBLANK_START_DOT);
        assert(PPU::HDMA_INIT_DOT < PPU::VISIBLE_DOT_START);
    }
    {
        Bus bus;
        bus.power();
        PPU ppu;
        ppu.attachBus(&bus);
        bus.attachPPU(&ppu);
        DMA dma;
        dma.attachBus(&bus);
        bus.attachDMA(&dma);
        dma.reset();
        bus.write(0x7E0200, 0x03);
        bus.write(0x7E0201, 0x05);
        bus.write(0x7E0202, 0x00);
        dma.writeRegister(0x4300, 0x00);
        dma.writeRegister(0x4301, 0x00);
        dma.writeRegister(0x4302, 0x00);
        dma.writeRegister(0x4303, 0x02);
        dma.writeRegister(0x4304, 0x7E);
        dma.setHDMAEnable(0x01);
        dma.startHDMAInit(0, 8);
        while (dma.hdmaActive()) dma.stepHDMA();
        dma.startHDMALine(1104, 8);
        while (dma.hdmaActive()) dma.stepHDMA();
        assert(dma.lastHDMAMasterClocks() == 32);
        assert(ppu.brightness() == 0x05);
        dma.startHDMALine(1104, 8);
        while (dma.hdmaActive()) dma.stepHDMA();
        assert(dma.lastHDMAMasterClocks() == 24);
        dma.startHDMALine(1104, 8);
        while (dma.hdmaActive()) dma.stepHDMA();
        assert(dma.lastHDMAMasterClocks() == 32);
    }
    {
        Bus bus;
        bus.power();
        PPU ppu;
        ppu.attachBus(&bus);
        bus.attachPPU(&ppu);
        DMA dma;
        dma.attachBus(&bus);
        bus.attachDMA(&dma);
        dma.reset();
        bus.write(0x7E0000, 0x01);
        bus.write(0x7E0001, 0x05);
        bus.write(0x7E0002, 0x01);
        bus.write(0x7E0003, 0x0A);
        bus.write(0x7E0004, 0x00);
        dma.writeRegister(0x4300, 0x00);
        dma.writeRegister(0x4301, 0x00);
        dma.writeRegister(0x4302, 0x00);
        dma.writeRegister(0x4303, 0x00);
        dma.writeRegister(0x4304, 0x7E);
        dma.setHDMAEnable(0x01);
        dma.startHDMAInit();
        while (dma.hdmaActive()) dma.stepHDMA();
        assert(dma.readRegister(0x4308) == 0x01);
        assert(dma.readRegister(0x4309) == 0x00);
        assert(dma.readRegister(0x430A) == 0x01);
        dma.startHDMALine();
        while (dma.hdmaActive()) dma.stepHDMA();
        assert(ppu.brightness() == 0x05);
        assert(dma.readRegister(0x4308) == 0x03);
        assert(dma.readRegister(0x4309) == 0x00);
        assert(dma.readRegister(0x430A) == 0x01);
        dma.startHDMALine();
        while (dma.hdmaActive()) dma.stepHDMA();
        assert(ppu.brightness() == 0x0A);
        assert(dma.readRegister(0x4308) == 0x05);
        assert(dma.readRegister(0x430A) == 0x00);
    }
    {
        Bus bus;
        bus.power();
        PPU ppu;
        ppu.attachBus(&bus);
        bus.attachPPU(&ppu);
        DMA dma;
        dma.attachBus(&bus);
        bus.attachDMA(&dma);
        dma.reset();
        bus.write(0x7E0100, 0x03);
        bus.write(0x7E0101, 0x06);
        bus.write(0x7E0102, 0x01);
        bus.write(0x7E0103, 0x0A);
        bus.write(0x7E0104, 0x00);
        dma.writeRegister(0x4300, 0x00);
        dma.writeRegister(0x4301, 0x00);
        dma.writeRegister(0x4302, 0x00);
        dma.writeRegister(0x4303, 0x01);
        dma.writeRegister(0x4304, 0x7E);
        dma.setHDMAEnable(0x01);
        dma.startHDMAInit();
        while (dma.hdmaActive()) dma.stepHDMA();
        assert(dma.readRegister(0x4308) == 0x01);
        dma.startHDMALine();
        while (dma.hdmaActive()) dma.stepHDMA();
        assert(ppu.brightness() == 0x06);
        assert(dma.readRegister(0x4308) == 0x02);
        assert(dma.readRegister(0x430A) == 0x02);
        dma.startHDMALine();
        while (dma.hdmaActive()) dma.stepHDMA();
        assert(ppu.brightness() == 0x06);
        assert(dma.readRegister(0x4308) == 0x02);
        assert(dma.readRegister(0x430A) == 0x01);
        dma.startHDMALine();
        while (dma.hdmaActive()) dma.stepHDMA();
        assert(ppu.brightness() == 0x06);
        assert(dma.readRegister(0x4308) == 0x03);
        assert(dma.readRegister(0x430A) == 0x01);
    }
    {
        Bus bus;
        bus.power();
        PPU ppu;
        ppu.attachBus(&bus);
        bus.attachPPU(&ppu);
        DMA dma;
        dma.attachBus(&bus);
        bus.attachDMA(&dma);
        dma.reset();
        bus.write(0x7E0000, 0x02);
        bus.write(0x7E0001, 0x01);
        bus.write(0x7E0002, 0x00);
        dma.writeRegister(0x4300, 0x00);
        dma.writeRegister(0x4301, 0x00);
        dma.writeRegister(0x4302, 0x00);
        dma.writeRegister(0x4303, 0x00);
        dma.writeRegister(0x4304, 0x7E);
        dma.setHDMAEnable(0x01);
        dma.startHDMAInit();
        while (dma.hdmaActive()) dma.stepHDMA();
        dma.writeRegister(0x4310, 0x00);
        dma.writeRegister(0x4311, 0x00);
        dma.writeRegister(0x4312, 0x10);
        dma.writeRegister(0x4313, 0x00);
        dma.writeRegister(0x4314, 0x7E);
        dma.writeRegister(0x4315, 0x10);
        dma.writeRegister(0x4316, 0x00);
        dma.startDMA(0x02, 0);
        assert(dma.dmaActive());
        dma.startHDMALine();
        assert(dma.hdmaActive());
        assert(dma.hdmaNextDelay() == DMA::HDMA_NESTED_GLOBAL_OVERHEAD);
    }
    {
        Bus bus;
        bus.power();
        PPU ppu;
        ppu.attachBus(&bus);
        bus.attachPPU(&ppu);
        DMA dma;
        dma.attachBus(&bus);
        bus.attachDMA(&dma);
        dma.reset();
        bus.write(0x7E0000, 0x01);
        bus.write(0x7E0001, 0x05);
        bus.write(0x7E0002, 0x00);
        dma.writeRegister(0x4300, 0x00);
        dma.writeRegister(0x4301, 0x00);
        dma.writeRegister(0x4302, 0x00);
        dma.writeRegister(0x4303, 0x00);
        dma.writeRegister(0x4304, 0x7E);
        dma.setHDMAEnable(0x01);
        dma.startHDMAInit();
        while (dma.hdmaActive()) dma.stepHDMA();
        bus.write(0x7E0010, 0x01);
        bus.write(0x7E0011, 0x02);
        bus.write(0x7E0012, 0x03);
        bus.write(0x7E0013, 0x04);
        bus.write(0x7E0020, 0x0C);
        dma.writeRegister(0x4302, 0x10);
        dma.writeRegister(0x4303, 0x00);
        dma.writeRegister(0x4304, 0x7E);
        dma.writeRegister(0x4305, 0x04);
        dma.writeRegister(0x4306, 0x00);
        dma.writeRegister(0x4310, 0x00);
        dma.writeRegister(0x4311, 0x00);
        dma.writeRegister(0x4312, 0x20);
        dma.writeRegister(0x4313, 0x00);
        dma.writeRegister(0x4314, 0x7E);
        dma.writeRegister(0x4315, 0x01);
        dma.writeRegister(0x4316, 0x00);
        dma.startDMA(0x03, 0);
        dma.stepDMA();
        dma.stepDMA();
        dma.stepDMA();
        assert(dma.readRegister(0x4305) == 0x04);
        dma.startHDMALine();
        assert(dma.hdmaActive());
        assert(dma.hdmaNextDelay() == DMA::HDMA_NESTED_GLOBAL_OVERHEAD);
        assert(dma.readRegister(0x4305) == 0x04);
        while (dma.hdmaActive()) dma.stepHDMA();
        assert(ppu.brightness() == 0x05);
        assert(dma.readRegister(0x4305) == 0x04);
        assert(dma.dmaActive());
        assert(dma.dmaResumeDelayAfterHDMA(7) == 0);
        dma.stepDMA();
        dma.stepDMA();
        dma.stepDMA();
        assert(dma.dmaActive());
        dma.stepDMA();
        assert(!dma.dmaActive());
        assert(dma.readRegister(0x4305) == 0x04);
        assert(dma.readRegister(0x4315) == 0x00);
        assert(ppu.brightness() == 0x0C);
    }
    {
        PPU ppu;
        Bus bus;
        DMA dma;
        bus.attachPPU(&ppu);
        bus.attachDMA(&dma);
        dma.attachBus(&bus);
        dma.setHDMAEnable(0);
        dma.startHDMAInit();
        assert(!dma.hdmaActive());
        dma.writeRegister(0x4300, 0x00);
        dma.writeRegister(0x4301, 0x00);
        dma.writeRegister(0x4304, 0x7E);
        dma.writeRegister(0x4308, 0x20);
        dma.writeRegister(0x4309, 0x00);
        dma.writeRegister(0x430A, 0x00);
        bus.write(0x7E0020, 0x0D);
        dma.setHDMAEnable(0x01);
        dma.startHDMALine();
        assert(dma.hdmaActive());
        while (dma.hdmaActive()) dma.stepHDMA();
        assert(ppu.brightness() != 0x0D);
        assert(dma.readRegister(0x430A) == 0xFF);
        dma.setHDMAEnable(0x01);
        dma.startHDMALine();
        assert(dma.hdmaActive());
        dma.setHDMAEnable(0x00);
        while (dma.hdmaActive()) dma.stepHDMA();
        assert(ppu.brightness() == 0x0D);
        dma.startHDMALine();
        assert(!dma.hdmaActive());
    }
    {
        Bus bus;
        bus.power();
        PPU ppu;
        ppu.attachBus(&bus);
        bus.attachPPU(&ppu);
        DMA dma;
        dma.attachBus(&bus);
        bus.attachDMA(&dma);
        dma.reset();
        bus.write(0x7E0000, 0x01);
        bus.write(0x7E0001, 0x05);
        bus.write(0x7E0002, 0x00);
        dma.writeRegister(0x4300, 0x00);
        dma.writeRegister(0x4301, 0x00);
        dma.writeRegister(0x4302, 0x00);
        dma.writeRegister(0x4303, 0x00);
        dma.writeRegister(0x4304, 0x7E);
        dma.setHDMAEnable(0x01);
        dma.startHDMAInit(3, 6);
        assert(dma.hdmaActive());
        assert(dma.hdmaNextDelay() == 5);
        while (dma.hdmaActive()) dma.stepHDMA();
        assert((dma.lastHDMAMasterClocks() % 6) == 0);
        dma.startHDMALine(1115, 12);
        assert(dma.hdmaActive());
        assert(dma.hdmaNextDelay() == 5);
        while (dma.hdmaActive()) dma.stepHDMA();
        assert((dma.lastHDMAMasterClocks() % 12) == 0);
    }
    {
        Bus bus;
        bus.power();
        PPU ppu;
        ppu.attachBus(&bus);
        bus.attachPPU(&ppu);
        DMA dma;
        dma.attachBus(&bus);
        bus.attachDMA(&dma);
        dma.reset();
        bus.write(0x7E0000, 0x01);
        bus.write(0x7E0001, 0x06);
        bus.write(0x7E0002, 0x00);
        dma.writeRegister(0x4300, 0x00);
        dma.writeRegister(0x4301, 0x00);
        dma.writeRegister(0x4302, 0x00);
        dma.writeRegister(0x4303, 0x00);
        dma.writeRegister(0x4304, 0x7E);
        dma.setHDMAEnable(0x01);
        dma.startHDMAInit();
        while (dma.hdmaActive()) dma.stepHDMA();
        const uint8_t captured = dma.hdmaEnable();
        dma.setHDMAEnable(0x00);
        dma.startHDMALineCaptured(captured, 1114, 8);
        assert(dma.hdmaActive());
        while (dma.hdmaActive()) dma.stepHDMA();
        assert(ppu.brightness() == 0x06);
        dma.startHDMALine(2478, 8);
        assert(!dma.hdmaActive());
    }
    std::cout << "phase19 HDMA request/capture timing accuracy ok\n";
    return 0;
}
